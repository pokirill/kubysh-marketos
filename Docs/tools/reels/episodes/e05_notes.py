"""П5 · 08.10 · «Заметки». Записывать все в заметки — подвиг; скриншот из банка, Кубыш раскладывает сам."""
from studio import *  # noqa
import props as P

ITEMS = [("кофе", "350"), ("такси", "420"), ("шаурма", "290"), ("метро", "62"), ("доставка", "890"), ("кофе", "350"), ("продукты", "1 240"),
         ("самокат", "180"), ("обед", "460"), ("подписка", "299"), ("кофе", "350"), ("такси", "560"), ("аптека", "740"), ("бар", "1 800")] * 4
CARD = "Карточки для стора 1.7 (сборка 100)/"


def build():
    ep = Ep("E05_Заметки", "classroom")
    dush = ep.actor("dush", "dush", 260, s=0.74, mirror=True, pointer=True)
    kub = ep.actor("kub", "kubysh", 1320, s=0.7)
    items = ITEMS[:47]
    st = {"out": 99}

    def notes(img, t, cam):
        o = st["out"]
        k = back(seg(t, 0.15, 0.45)) * (1 - eio(seg(t, o, o + 0.3)))
        if k < 0.02: return
        im = scaled(P.notes_card(items, scroll=min(max(0, t - 0.2) * 900, 47 * 62 - 700)), 0.62 * k)
        comp(img, im, 560 - im.width / 2, 800 - im.height / 2)
    ep.add(0, 99, "screen", notes)
    ep.counter(0.5, 3.2, 0, 47, 700, 1190, size=120, suffix=" трат", color=(255, 214, 74), dur=1.4)
    ep.chat(0.0, "me", "47 трат в заметках. А сколько можно завтра, все равно непонятно", t1=3.4)
    dush.expr(0, "teacher"); ep.shot(0, "wide", z=1.1)
    t0, t1 = ep.line("dush", "Записывай каждую. Это *дисципл+ина.*", at=0.9)
    ep.chalk(t0 + 0.3, "Записывать каждую!", 130, 380, 70)
    tk = t1 + 0.05
    kub.go(tk, 800, hop=150, step=320); kub.expr(tk, "neutral")
    ep.cursor = tk + 0.8
    t0, t1 = ep.line("kub", "Записывать всё в заметки это подвиг. Но можно *пр+още.*", cap="Записывать все в заметки это подвиг. Но можно *проще*")
    ep.shot(t0, "kub"); kub.expr(t0, "proud"); st["out"] = t1 - 0.3
    t0, t1 = ep.line("kub", "Скинь скриншот из банка. Я разложу по категориям и пересчитаю *з+автра.*",
                     cap="Скинь скриншот из банка. Я разложу по категориям и пересчитаю *завтра*", y=170, size=66)
    ep.shot(t0, "wide", z=1.04, dur=0.3)
    ep.card(t0 + 0.2, t0 + 2.0, CARD + "05_Траты_скриншотом.png", keys=[(t0 + 0.2, (207, 1217, 640, 1717), 420, 760, 470)])
    ep.sfx(t0 + 1.8, "thwip", 0.4)
    ep.card(t0 + 2.0, t1 + 2.2, CARD + "06_Сам_разложит.png",
            keys=[(t0 + 2.0, (210, 1183, 1083, 1717), 520, 720, 900), (t1 + 0.2, (210, 1183, 1083, 1907), 520, 760, 900)],
            marks=[(t0 + 2.4, (220, 1200, 1075, 1700), MINT), (t1 + 0.6, (220, 1760, 1075, 1905), YEL)])
    ep.counter(t1 + 0.8, t1 + 2.2, 0, 2800, 540, 1240, size=140, prefix="завтра ")
    for a in (kub, dush): a.look(t0 + 0.3, ("screen", 520, 760)); a.look(t1 + 2.2, None)
    ep.chat(t1 + 2.3, "me", "Минута? Серьезно?", t1=t1 + 4.6)
    ep.cursor = t1 + 3.2
    t0, t1 = ep.line("kub", "Вечер остаётся *теб+е.*", cap="Вечер остается *тебе*")
    ep.shot(t0, "kub", z=1.45, dur=0.2); kub.expr(t0, "smug", wink="R")
    ep.sticker(t0 + 0.2, t1 + 0.6, P.sparkle(), "kub", dx=150, dy=-30)
    te = t1 + 0.35
    ep.shot(te, "wide", dur=0.4); dush.expr(te, "skeptic")
    ep.pill(te, te + 2.3, "Отправь тому, кто ведет траты в заметках", 540, 520, size=42)
    ep.pill(te + 0.3, te + 2.3, "Завтра: 2 часа ночи", 540, 640, size=50, bg=(30, 130, 88), fg=(255, 255, 255))
    ep.dur = te + 2.4; ep.cover_t = 1.0
    return ep
