"""К4 · «ДР Маши: одна суббота, две версии». Версия 1: забыла про ДР, траты мимо плана, праздник в телефоне.
Версия 2: 10-го добавила ДР в план, накануне Кубыш напомнил, праздник без телефона. Боль учета: предстоящие траты.
Записи экрана (профиль Ксюши в симуляторе) снимаются 10.10: до этого вместо них заглушки.
"""
from studio import *  # noqa
import audio

R = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Рилсы Ксюша/"
CL, K2 = R + "K04_клипы/", R + "K02_клипы/"
SCR = R + "Запись_экрана/"
VO = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Голоса/K04/"
AMB = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Голоса/Фон/cafe_45s.wav"
BANK = dict(icon="₽", color=(52, 120, 246))
DARK = dict(bg=(60, 50, 90), fg=WHITE)
RED = dict(bg=(170, 40, 60), fg=WHITE)
GREEN = dict(bg=(30, 130, 88), fg=WHITE)


def build():
    ep = Ep("K04_ДР_Маши", "studio")
    ep.vgain = 0.95
    from PIL import Image as _I
    ep.avatars = {w: _I.open(R + f"Референсы/avatar_{w}.png").convert("RGBA") for w in ("ksy", "kubysh", "dush")}

    # 0 · Кубыш-автор в камеру
    a0, a1 = ep.say("kubysh", "", cap="В субботу у Маши *день рождения.* Смотри *две версии*", at=0.2, file=VO + "к1_версии.wav", y=1400)
    ep.pill(0.3, a1, "Одна суббота. Две версии", 540, 760, size=60)
    s1 = a1 + 0.15; ep.clip(0, s1, K2 + "S1.mp4", "S1")

    # 1 · Версия 1: забыла. Пятница, 23:40, траты мимо плана
    ep.pill(s1, s1 + 3.2, "Версия 1 · Забыла", 540, 760, size=56, **RED)
    ep.pill(s1 + 0.2, s1 + 3.2, "Пятница, 23:40", 540, 870, size=44, **DARK)
    ep.pushes([(s1 + 0.4, "Банк", "Подарок −8 000 ₽"), (s1 + 1.1, "Банк", "Цветы −2 500 ₽"), (s1 + 1.8, "Банк", "Такси −2 000 ₽")], s1 + 3.2, **BANK)
    s2 = s1 + 3.3; ep.clip(s1, s2, K2 + "S2.mp4", "S2", src_t0=0.5)

    # 2 · караоке: все поют, Ксюша в телефоне; Душная на своем крупном плане
    ep.pill(s2 + 0.1, s2 + 1.8, "Караоке. Поют Агутина", 540, 330, size=50, **DARK)
    s3 = s2 + 1.9; ep.clip(s2, s3, CL + "C3.mp4", "C3")
    b0, b1 = ep.say("dush", "", cap="Двенадцать тысяч мимо плана… а до зарплаты еще *неделя*", at=s3 + 0.1, file=VO + "д1.mp3", y=1400)
    # губы в клипе двигаются на ~1,8–2,7 и 3,6–4,4 с: две половины реплики на два окна
    cut = b0 + 2.15; s4 = b1 + 0.1
    ep.clip(s3, cut, CL + "C4.mp4", "C4", src_t0=1.6)
    ep.clip(cut, s4, CL + "C4.mp4", "C4b", src_t0=3.45)

    # 3 · экран: перерасход пересчитан (запись 10.10)
    c0, c1 = ep.say("kubysh", "", cap="Я все *пересчитал.* Но праздник ты провела *в телефоне*", at=s4 + 0.15, file=VO + "к2_пересчитал.wav", y=1560)
    s5 = c1 + 0.2; ep.clip(s4, s5, SCR + "K04_перерасход.mp4", "Экран: перерасход 12 500 разложен, с завтра меньше в день")

    # 4 · Версия 2: заложила 10-го (запись 10.10)
    ep.pill(s5, s5 + 3.3, "Версия 2 · Заложила", 540, 760, size=56, **GREEN)
    d0, d1 = ep.say("kubysh", "", cap="А тут *десятого* ты добавила день рождения *в план*", at=s5 + 0.15, file=VO + "к3_десятого.wav", y=1560)
    s6 = d1 + 0.2; ep.clip(s5, s6, SCR + "K04_ДР_в_плане.mp4", "Экран: «Что еще предстоит оплатить» → ДР Маши 12 500")

    # 5 · накануне Кубыш напоминает (текст пуша сверить с приложением)
    ep.notif(s6 + 0.1, s6 + 2.4, "Кубыш", "Завтра ДР Маши · 12 500 уже в плане", icon="К", color=(30, 130, 88))
    e0, e1 = ep.say("kubysh", "", cap="А *накануне* я напомнил", at=s6 + 0.4, file=VO + "к4_напомнил.wav", y=1400)
    s7 = e1 + 0.2; ep.clip(s6, s7, K2 + "S4.mp4", "S4", src_t0=1.0)

    # 6 · тот же праздник: поет, телефон экраном вниз; Маша замечает
    ep.pill(s7 + 0.3, s7 + 2.3, "Маша: «Ты сегодня какая-то спокойная»", 540, 330, size=44, **DARK)
    f0, f1 = ep.say("ksy", "", cap="Я просто *заранее* все знала", at=s7 + 2.4, file=VO + "кс_знала.mp3", y=1400)
    s8 = f1 + 0.3; ep.clip(s7, s8, CL + "C7.mp4", "C7")

    # 7 · поворот: Душная молча ест торт; итог и затравка К5
    ep.pill(s8 + 0.8, s8 + 3.2, "Разница — одна строчка в плане", 540, 760, size=52)
    ep.pill(s8 + 1.2, s8 + 3.2, "Кубыш · бесплатно до следующей зарплаты", 540, 330, size=40, **GREEN)
    ep.pill(s8 + 1.8, s8 + 3.2, "Дальше: куда ушли 230 тысяч?", 540, 1400, size=50, **DARK)
    ep.dur = s8 + 3.2; ep.clip(s8, ep.dur, CL + "C8.mp4", "C8")

    amb = audio.load(AMB)[:int(ep.dur * audio.SR)]
    ep.extra = [(s2, ep.duck(amb[int(s2 * audio.SR):int(s5 * audio.SR)], depth=0.25), 0.35),
                (s7, ep.duck(amb[int(s7 * audio.SR):], depth=0.25), 0.35)]
    ep.cover_t = 1.0
    return ep
