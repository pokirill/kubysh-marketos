"""К2 · 13.10 · «Пятница», ~26 с. Подруги зовут в Питер, Душная шепчет про еду, Кубыш считает «что будет, если поехать».
Правила Кирилла после К1: Кубыш — автор и в кадре с первой секунды, Душная весь ролик на плече, только клипы, без точек в конце.
Клипы Kling 3.0, голоса ElevenLabs (Кубыш Holden и Ксюша Xenia одним дублем, нарезка по паузам; Душная — клон).
"""
from studio import *  # noqa

R = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Рилсы Ксюша/"
CL = R + "K02_клипы/"
VO = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Голоса/K02/"
SH = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Скриншоты 1.7/Из симулятора/"


def build():
    ep = Ep("K02_Пятница", "studio")
    ep.vgain = 0.95
    from PIL import Image as _I
    ep.avatars = {w: _I.open(R + f"Референсы/avatar_{w}.png").convert("RGBA") for w in ("ksy", "kubysh", "dush")}

    # 1 · хук: Кубыш в кадре и рассказывает, подруги зовут, Душная начинает
    ep.notif(0.1, 3.4, "Девочки", "Едем в Питер на выходные?", icon="Д", color=(126, 92, 214))
    ep.pill(0.2, 3.0, "Зовут в Питер, а до аванса 12 дней", 540, 760, size=46)
    a0, a1 = ep.say("kubysh", "", cap="Это *Ксюша.* Слышишь, кто сейчас начнет?", at=0.3, file=VO + "к1_ксюша.wav", y=1400)
    s1b = a1 + 0.1; ep.clip(0, s1b, CL + "S1.mp4", "S1")
    # Душная говорит только на своем крупном плане: в клипе она шепчет все 5 с, губы и голос совпадают
    b0, b1 = ep.say("dush", "", cap="Двенадцать тысяч… а вдруг потом на еду не *хватит?*", at=s1b + 0.1, file=VO + "д1_хук.wav", y=1400)
    # губы в клипе двигаются на 0,7–2,0 и 3,5–5,0 с: «Двенадцать тысяч…» на первое окно, после паузы склейка на второе
    cut = b0 + 1.5; s2 = b0 + 3.4
    ep.clip(s1b, cut, CL + "S1b.mp4", "S1b", src_t0=0.6)
    ep.clip(cut, s2, CL + "S1b.mp4", "S1c", src_t0=3.25)

    # 2 · Ксюша пишет «я пас» и стирает
    ep.chat(s2 + 0.05, "me", "я пас", t1=s2 + 1.0)
    s3 = s2 + 1.1; ep.clip(s2, s3, CL + "S2.mp4", "S2", src_t0=1.0)

    # 3 · действие: Кубыш перепрыгивает к ней
    c0, c1 = ep.say("kubysh", "", cap="Давай посмотрим, что будет, если *поехать*", at=s3 + 0.1, file=VO + "к2_посмотрим.wav", y=1400)
    ep.sfx(s3 + 0.4, "hop", 0.5)
    s4 = c1 + 0.1; hop = s3 + 2.0  # после 2 с камера Kling уезжает и Душная пропадает: режем на прыжке, дальше S4
    ep.clip(s3, hop, CL + "S3.mp4", "S3")

    # 4 · экран «Прикинуть покупку»: 12 000 есть, в день 4 064 → 3 947
    d0, d1 = ep.say("kubysh", "", cap="В день станет на *117* меньше. До аванса *хватает*", at=s4 + 0.2, file=VO + "к3_цифры.wav", y=170, size=74)
    ep.card(s4 + 0.05, d1 + 0.1, SH + "afford_100.png", keys=[(s4 + 0.05, (40, 1120, 1170, 2220), 540, 960, 960)],
            marks=[(s4 + 0.4, (95, 1180, 830, 1280), YEL), (d0 + 0.9, (790, 1700, 1110, 1790), MINT)])
    s5 = d1 + 0.15; ep.clip(hop, s5, CL + "S4.mp4", "S4")

    # 5 · решение за ней
    e0, e1 = ep.say("ksy", "", cap="Сто рублей в день за Питер с *девочками?*", at=s5 + 0.2, file=VO + "кс2_питер.wav", y=1400)
    f0, f1 = ep.say("ksy", "", cap="Всё, я *еду!*", at=e1 + 0.15, file=VO + "кс3_еду.wav", y=1400, size=90)
    ep.chat(f0 + 0.05, "me", "ЕДУ!", t1=f1 + 1.0)
    s6 = f1 + 0.1; ep.clip(s5, s6, CL + "S5.mp4", "S5")

    # 6 · поворот: в «Сапсане» на плече Душная в очках
    g0, g1 = ep.say("kubysh", "", cap="Даже *Душная* поехала", at=s6 + 0.15, file=VO + "к5_душная.wav", y=1400)
    ep.sfx(s6, "swish", 0.35)
    s7 = g1 + 0.25; ep.clip(s6, s7, CL + "S6.mp4", "S6")

    # 7 · Кубыш подписывает ролик слоганом, затравка на К3
    h0, h1 = ep.say("kubysh", "", cap="Бюджет под твою *жизнь,* а не наоборот", at=s7 + 0.15, file=VO + "к6_слоган.wav", y=1400, size=74)
    ep.pill(s7 + 0.2, h1 + 1.3, "Кубыш · бесплатно до следующей зарплаты", 540, 330, size=40, bg=(30, 130, 88), fg=WHITE)
    ep.pill(h0 + 1.2, h1 + 1.3, "Дальше: зарплата пришла, а Душная тоже", 540, 760, size=46, bg=(60, 50, 90), fg=WHITE)
    ep.dur = h1 + 1.3; ep.clip(s7, ep.dur, CL + "S7.mp4", "S7")
    ep.cover_t = 1.2
    return ep
