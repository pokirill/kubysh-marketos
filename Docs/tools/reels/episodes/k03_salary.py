"""К3 · 15.10 · «Зарплата». Хук: зарплата живет 7 дней. Сначала аренда и кайфы, потом коммуналка и кредитка, на Японию ноль.
Кубыш отматывает к 10.10 и раскладывает получку: обязательное и Япония сразу, остальное по 2 330 в день, и напоминает
про ДР Маши (подводка к К4). Правила Кирилла: Кубыш автор с первой секунды, Душная говорит только на своем крупном плане.
"""
from studio import *  # noqa

R = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Рилсы Ксюша/"
CL, CL2 = R + "K03_клипы/", R + "K02_клипы/"
VO = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Голоса/K03/"
SH = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Скриншоты 1.7/Из симулятора/"
BANK = dict(icon="₽", color=(52, 120, 246))
DARK = dict(bg=(60, 50, 90), fg=WHITE)


def date(ep, t0, t1, text):
    ep.pill(t0, t1, text, 540, 1030, size=42, **DARK)


def build():
    ep = Ep("K03_Зарплата", "studio")
    ep.vgain = 0.95
    from PIL import Image as _I
    ep.avatars = {w: _I.open(R + f"Референсы/avatar_{w}.png").convert("RGBA") for w in ("ksy", "kubysh", "dush")}

    # 1 · хук: зарплата пришла, Кубыш в кадре и иронизирует, траты летят уже в лифте
    a0, a1 = ep.say("kubysh", "", cap="Десятое. Ксюша *богатая.* Ровно на *неделю*", at=0.3, file=VO + "к1_богатая.wav", y=1400)
    ep.pill(0.3, 2.6, "Зарплата живет 7 дней. Проверим?", 540, 760, size=50)
    s2 = a1 + 0.05
    spree = [(0.15, "Банк", "Зачисление зарплаты +95 000 ₽"), (2.7, "Банк", "Аренда −45 000 ₽"), (s2 + 0.1, "Банк", "Маркетплейс −8 400 ₽"),
             (s2 + 0.55, "Банк", "Бар −4 600 ₽"), (s2 + 1.0, "Банк", "Суши −2 900 ₽"), (s2 + 1.45, "Банк", "Такси −1 100 ₽")]
    ep.pushes(spree, s2 + 2.3, **BANK)
    bal = [95000, 50000, 41600, 37000, 34100, 33000]
    ep.balance([(0.0, 0)] + [(t, v) for (t, _, _), v in zip(spree, bal)], s2 + 2.3)
    date(ep, 0.2, s2, "10 октября"); date(ep, s2, s2 + 2.3, "12 октября")
    ep.clip(0, s2, CL + "C1.mp4", "C1")
    s3 = s2 + 2.3; ep.clip(s2, s3, CL + "C2.mp4", "C2")

    # 2 · Душная на своем крупном плане (клип К2, губы на 0,7–2,0 и 3,5–5,0 с)
    b0, b1 = ep.say("dush", "", cap="Ну что, *богачка…* увидимся через *неделю*", at=s3 + 0.1, file=VO + "д1_богачка.wav", y=1400)
    cut = b0 + 1.35; s4 = b0 + 3.15
    ep.clip(s3, cut, CL2 + "S1b.mp4", "D1", src_t0=0.6)
    ep.clip(cut, s4, CL2 + "S1b.mp4", "D2", src_t0=3.4)

    # 3 · обязательные платежи всплывают, на Японию ноль
    bills = [(s4 + 0.1, "Банк", "Коммуналка −7 800 ₽"), (s4 + 0.5, "Банк", "Кредитка −9 000 ₽"), (s4 + 0.9, "Банк", "Связь и подписки −1 900 ₽")]
    ep.pushes(bills, s4 + 3.2, **BANK)
    ep.balance([(s4, 33000)] + [(t, v) for (t, _, _), v in zip(bills, [25200, 16200, 14300])], s4 + 3.2)
    date(ep, s4 + 0.1, s4 + 3.2, "17 октября")
    c0, c1 = ep.say("ksy", "", cap="Ой… *коммуналка.* А на Японию *ноль*", at=s4 + 0.3, file=VO + "кс1_коммуналка.wav", y=1400)
    # 4 · Япония ускользает, до аванса ужиматься (поверх того же кадра, без отдельной сцены — короче)
    ep.pill(c1 - 0.6, c1 + 1.0, "Япония ускользает", 540, 840, size=60, **DARK)
    ep.pill(c1 - 0.2, c1 + 1.0, "До аванса 1 790 ₽ в день", 540, 1170, size=56, bg=(150, 40, 60), fg=WHITE)
    s6 = c1 + 1.1; ep.clip(s4, s6, CL + "C3.mp4", "C3")

    # 5 · действие: Кубыш щелкает, перемотка к 10.10
    d0, d1 = ep.say("kubysh", "", cap="Давай *отмотаем*", at=s6 + 0.1, file=VO + "к2_отмотаем.wav", y=1400)
    rw = d1 + 0.1; ep.clip(s6, rw, CL + "C5.mp4", "C5", src_t0=1.8)
    ep.sfx(rw, "whoosh", 0.7); ep.sfx(rw + 0.5, "whoosh", 0.6)
    ep.clip(rw, rw + 0.5, CL + "C2.mp4", "R1", src_t0=2.4, speed=-4)
    ep.clip(rw + 0.5, rw + 1.1, CL + "C1.mp4", "R2", src_t0=4.4, speed=-6)
    s7 = rw + 1.1; date(ep, rw, s7 + 1.0, "10 октября")

    # 6 · план получки: обязательное и Япония сразу, остальное по 2 330
    e0, e1 = ep.say("kubysh", "", cap="Обязательное и Япония — *сразу.* Остальное — по *2 330* в день", at=s7 + 0.2, file=VO + "к3_план.wav", y=170, size=72)
    ep.card(s7 + 0.1, e1 + 0.15, SH + "plan.png", keys=[(s7 + 0.1, (38, 1370, 1168, 2215), 540, 960, 960)],
            marks=[(e0 + 0.6, (113, 2029, 1127, 2179), YEL), (e0 + 3.4, (450, 1390, 752, 1522), MINT)])
    s8 = e1 + 0.15; ep.clip(s7, s8, CL + "C1.mp4", "C1b", src_t0=0.8)

    # 7 · подводка к К4: день рождения Маши
    f0, f1 = ep.say("kubysh", "", cap="А в субботу у Маши *день рождения.* Подарок заложим?", at=s8 + 0.1, file=VO + "к4_маша.wav", y=170, size=72)
    ep.card(s8, f1 + 0.2, SH + "plan.png", keys=[(s8, (38, 1007, 1168, 1259), 540, 900, 980)],
            marks=[(f0 + 1.6, (834, 1059, 1127, 1157), YEL)])

    # 8 · финал: суши в бюджете дня, Душная спит, слоган и затравка К4
    g0 = f1 + 0.3; g1 = g0 + 2.4  # слоган плашкой, без голоса: экономим 3 с
    ep.pill(g0, g1, "Бюджет под твою жизнь, а не наоборот", 540, 1400, size=44)
    ep.pill(g0 + 0.2, g1, "Кубыш · бесплатно до следующей зарплаты", 540, 330, size=40, bg=(30, 130, 88), fg=WHITE)
    ep.pill(g0 + 0.8, g1, "Дальше: ДР Маши. Две версии", 540, 760, size=50, **DARK)
    ep.dur = g1; ep.clip(s8, ep.dur, CL + "C8.mp4", "C8")
    ep.cover_t = 1.2
    return ep
