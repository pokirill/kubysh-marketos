"""К1 · «Знакомьтесь, Ксюша». Запуск образа Ксюши: кофейня, Душная на стойке, две цели в плане, решение за ней.

Клипы Higgsfield кладутся в CL как S1.mp4…S7.mp4, живые реплики Ксюши — в VO как K01_1.m4a…K01_3.m4a.
Пока файлов нет, вместо клипов заглушки с описанием шота, вместо голоса Ксюши черновой синтез (аниматик).
Стойка кофейни в клипах S1 и S6 — на уровне COUNTER (31% от низа кадра), камера в этих шотах неподвижна.
"""
from studio import *  # noqa
import props as P

CL = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Рилсы Ксюша/K01_клипы/"
VO = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Голоса/Ксюша/"
COUNTER = 1330
SHOTS = {
    "S1": "S1 · кофейня, утро. Ксюша у стойки смотрит на меню и сомневается. Левая часть стойки пустая: там стоит Душная",
    "S2": "S2 · крупно: Ксюша косится на стойку, вздыхает с улыбкой и говорит в камеру (реплика 1, липсинк)",
    "S3": "S3 · по пояс: Ксюша с телефоном в мятном чехле говорит в камеру (реплика 2, липсинк)",
    "S4": "S4 · крупно руки с телефоном, кофейня размыта (сверху ляжет экран целей)",
    "S5": "S5 · Ксюша улыбается и поворачивается к бариста за кадром (реплика 3, липсинк)",
    "S6": "S6 · Ксюша тихо смеется, глядя на стойку, где спорят жабы. Стойка пустая в нижней трети",
    "S7": "S7 · Ксюша выходит из кофейни на солнечную улицу с большим латте, камера едет назад",
}


def build():
    ep = Ep("K01_Знакомьтесь_Ксюша", "studio")
    dush = ep.actor("dush", "dush", 220, s=0.42, mirror=True, ground=COUNTER, floor=False)
    kub = ep.actor("kub", "kubysh", 1300, s=0.42, ground=COUNTER, floor=False, hidden=True)
    cl = lambda k, a, b: ep.clip(a, b, CL + k + ".mp4", SHOTS[k])

    # S1 · хук: Душная на стойке
    dush.expr(0, "teacher")
    t0, t1 = ep.line("dush", "*Так!* Опять кофе? А Япония сама себя не *накоп+ит.*", at=0.3, y=1440)
    dush.react(t0, "puff")
    s1 = t1 + 0.2; cl("S1", 0, s1)
    # S2–S3 · Ксюша в камеру
    dush.show(s1, False)
    ep.cursor = s1 + 0.15
    a0, a1 = ep.say("ksy", "Это моя жаба. *Душит* за каждый кофе.", file=VO + "K01_1.m4a")
    s2 = a1 + 0.15; cl("S2", s1, s2)
    b0, b1 = ep.say("ksy", "А у меня две цели: *айфон* и *Япония.*", file=VO + "K01_2.m4a")
    s3 = b1 + 0.15; cl("S3", s2, s3)
    # S4 · экран целей, Кубыш впрыгивает на стойку
    kub.show(s3); kub.go(s3, 820, hop=120, step=300); kub.expr(s3, "proud")
    ep.cursor = s3 + 0.6
    c0, c1 = ep.line("kub", "Обе цели в *пл+ане.* А кофе из бюджета дня, не из *Японии.*", y=170, size=70)
    s4 = c1 + 0.35; cl("S4", s3, s4)
    ep.card(s3 + 0.1, s4, "Из симулятора/goals_top_100.png",
            keys=[(s3 + 0.1, (0, 700, 1320, 2600), 520, 800, 560), (c0 + 0.1, (40, 1690, 1280, 2620), 520, 760, 900)],
            marks=[(c0 + 0.6, (100, 1828, 320, 1880), MINT), (c0 + 1.1, (100, 2455, 320, 2510), MINT)])
    kub.look(s3 + 0.5, ("screen", 520, 760))
    # S5 · решение Ксюши
    kub.show(s4, False)
    ep.cursor = s4 + 0.1
    d0, d1 = ep.say("ksy", "Тогда латте. *Большой.*", file=VO + "K01_3.m4a")
    s5 = d1 + 0.3; cl("S5", s4, s5)
    # S6 · жабы спорят на стойке
    dush.show(s5); kub.show(s5); kub.place(s5, 820); kub.look(s5, None)
    dush.expr(s5, "angry"); kub.expr(s5, "smug")
    ep.cursor = s5 + 0.2
    e0, e1 = ep.line("dush", "*Так!* Кто *разреш+ил?*", y=1440)
    f0, f1 = ep.line("kub", "Никто. Тут решают *не жабы.*", y=1440, gap=0.1)
    kub.look(f0, "dush"); kub.expr(f0, "proud")
    s6 = f1 + 0.3; cl("S6", s5, s6)
    # S7 · улица и титры
    dush.show(s6, False); kub.show(s6, False)
    cl("S7", s6, s6 + 3.2)
    ep.pill(s6 + 0.2, s6 + 3.1, "Ксюша · две цели · ноль вины за кофе", 540, 520, size=48)
    ep.pill(s6 + 0.6, s6 + 3.1, "Скоро: от зарплаты до аванса с Ксюшей", 540, 640, size=44, bg=(30, 130, 88), fg=(255, 255, 255))
    ep.pill(s6 + 1.0, s6 + 3.1, "Кубыш · App Store", 540, 750, size=36)
    ep.dur = s6 + 3.2; ep.cover_t = 1.2
    return ep
