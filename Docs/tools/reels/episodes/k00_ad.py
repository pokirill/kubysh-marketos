"""Продающий ролик «Кубыш» (~27 с), собран из клипов К1–К3 без новых генераций видео.
Логика (Кирилл, 07.10): из-за тревоги и отсутствия плана кажется, что не хватит, и мы отказываем себе в мелочах →
Кубыш дает систему: куда уходят деньги, разложить получку, сколько есть на сегодня, когда накопишь на каждую цель →
суши, Питер и Япония в плане без стресса. Next Move: снимаем cognitive load и негативные эмоции, бьем в идентичность.
"""
from studio import *  # noqa

R = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Рилсы Ксюша/"
K1, K2, K3 = R + "K01_клипы/", R + "K02_клипы/", R + "K03_клипы/"
VO = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Голоса/Реклама/"
DV = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Голоса/K01/3_душная_авдруг.mp3"
CARDS = "/Users/kirillpopov/Documents/Кубыш доки и артефакты /Скриншоты 1.7/Карточки для стора 1.7 (сборка 100)/"
DARK = dict(bg=(60, 50, 90), fg=WHITE)


def build():
    ep = Ep("K00_Реклама_Кубыш", "studio")
    ep.vgain = 0.95
    from PIL import Image as _I
    ep.avatars = {w: _I.open(R + f"Референсы/avatar_{w}.png").convert("RGBA") for w in ("ksy", "kubysh", "dush")}

    # 1 · хук: Душная шепчет на своем крупном плане (губы в клипе на 0,7–2,0 с)
    ep.pill(0.1, 2.3, "Отказываешь себе в мелочах?", 540, 760, size=56)
    a0, a1 = ep.say("dush", "", cap="А вдруг… а вдруг не *хватит?*", at=0.15, file=DV, y=1400)
    s2 = a1 + 0.25; ep.clip(0, s2, K2 + "S1b.mp4", "D", src_t0=0.6)

    # 2 · отказы нарезкой, Кубыш называет причину
    b0, b1 = ep.say("kubysh", "", cap="Знакомо? Это не жадность. Это тревога *без плана*", at=s2 + 0.1, file=VO + "р1_знакомо.wav", y=1400)
    cuts = [(K1 + "S3a.mp4", 0.5, "Обед с коллегами? Нет"), (K1 + "S3b.mp4", 0.5, "Корзина? Удалить"), (K2 + "S2.mp4", 1.0, "Питер? Я пас")]
    seg = (b1 + 0.2 - s2) / len(cuts)
    for i, (path, src, label) in enumerate(cuts):
        t = s2 + i * seg; ep.clip(t, t + seg, path, f"N{i}", src_t0=src); ep.sfx(t, "swish", 0.3)
        ep.pill(t + 0.1, t + seg - 0.05, label, 540, 330, size=50, **DARK)
    s3 = b1 + 0.2

    # 3 · Кубыш щелкает: зарплата превращается в план
    c0, c1 = ep.say("kubysh", "", cap="Я *Кубыш.* Я превращаю зарплату *в план*", at=s3 + 0.1, file=VO + "р2_план.wav", y=1400)
    s4 = c1 + 0.15; ep.clip(s3, s4, K3 + "C5.mp4", "C5", src_t0=0.6)

    # 4 · система: четыре экрана подряд, у каждого своя фраза
    beats = [("р3а_куда.wav", "07_Куда_уходят_деньги.png", "Покажу, куда уходят *деньги*"),
             ("р3б_разложу.wav", "02_План_с_получки.png", "Разложу *получку*"),
             ("р3в_сегодня.wav", "01_Сколько_тратить.png", "Скажу, сколько есть на *сегодня*"),
             ("р3г_цели.wav", "03_Когда_накопишь.png", "И когда накопишь на *каждую цель*")]
    t = s4
    for f, card, cap in beats:
        d0, d1 = ep.say("kubysh", "", cap=cap, at=t + 0.1, file=VO + f, y=1640, size=68)
        e = d1 + 0.15
        ep.card(t, e, CARDS + card, keys=[(t, (0, 0, 1290, 1900), 540, 900, 900), (t + 0.6, (100, 560, 1190, 1900), 540, 900, 980)])
        t = e
    ep.clip(s4, t, K2 + "S4.mp4", "S4")
    s5 = t

    # 5 · что это дает: суши, Питер, Япония в плане
    g0, g1 = ep.say("kubysh", "", cap="Суши, Питер, Япония — все *в плане.* Без *стресса*", at=s5 + 0.1, file=VO + "р4_суши.wav", y=1400)
    q = (g1 + 0.2 - s5) / 3
    ep.clip(s5, s5 + q, K3 + "C8.mp4", "C8", src_t0=0.5)
    ep.clip(s5 + q, s5 + 2 * q, K2 + "S6.mp4", "S6", src_t0=1.0)
    ep.clip(s5 + 2 * q, s5 + 3 * q, K3 + "C4.mp4", "C4r", src_t0=4.6, speed=-2.2)  # постер с Японией возвращается на стену
    s6 = g1 + 0.2

    # 6 · Кубыш в камеру: слоган и оффер
    h0, h1 = ep.say("kubysh", "", cap="Бюджет под твою *жизнь,* а не наоборот", at=s6 + 0.15, file=VO + "р5_слоган.wav", y=1400, size=74)
    ep.pill(s6 + 0.3, h1 + 1.6, "Кубыш · бесплатно до следующей зарплаты", 540, 330, size=40, bg=(30, 130, 88), fg=WHITE)
    ep.pill(h1 + 0.1, h1 + 1.6, "Скачай в App Store", 540, 760, size=56)
    ep.dur = h1 + 1.6; ep.clip(s6, ep.dur, K2 + "S7.mp4", "S7")
    ep.cover_t = 1.0
    return ep
